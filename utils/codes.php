/**
 * وضعیت تأیید قالب، مقدار Status در پاسخ TokenList.
 *
 * پنل کاربری چهار حالت نشان می‌دهد و بین دو نوع رد شدن فرق می‌گذارد، ولی
 * API هر دو را ۳ برمی‌گرداند. فقط مقدار ۲ قابل ارسال است.
 */
const PR_TEMPLATE_STATUS = [
    1 => 'در انتظار بررسی',
    2 => 'تأیید شده',
    3 => 'رد شده',
];

/** وضعیت قالبی که می‌شود با آن پیامک فرستاد. */
const PR_TEMPLATE_SENDABLE = 2;

function pr_status_label(int $code): string
{
    return PR_STATUS_CODES[$code] ?? "وضعیت ناشناخته ($code)";
}

/** pending | final | not-sent | not-found */
function pr_status_disposition(int $code): string
{
    return PR_STATUS_DISPOSITION[$code] ?? 'pending';
}

/** آیا باید دوباره استعلام کرد یا وضعیت دیگر تغییر نمی‌کند. */
function pr_status_is_pending(int $code): bool
{
    return pr_status_disposition($code) === 'pending';
}

function pr_template_status_label(int $code): string
{
    return PR_TEMPLATE_STATUS[$code] ?? "وضعیت ناشناخته ($code)";
}

/**
 * تکلیف هر کد خطا با تلاش دوباره.
 *
 * متن فارسی خطاها اینجا نیست، چون خود سرویس آن را در فیلد Error برمی‌گرداند
 * و نگه داشتن نسخهٔ دوم فقط باعث واگرایی می‌شود. چیزی که سرویس نمی‌گوید و
 * برنامه لازم دارد، همین است: تلاش دوباره فایده دارد یا نه.
 *
 *   never        تا اصلاح نکنید بی‌فایده است
 *   backoff      با تأخیر فزاینده دوباره تلاش کنید
 *   limit-reset  تا آزاد شدن سهمیه صبر کنید
 *
 * فهرست بسته است. هر کد ناشناخته‌ای را مثل ۱۰۰ رفتار کنید.
 */
const PR_ERROR_RETRY = [
    1  => 'never',        // ApiKey نادرست
    2  => 'never',        // وب‌سرویس فعال نیست
    3  => 'never',        // کاربر فعال نیست
    4  => 'backoff',      // API موقتاً غیرفعال
    5  => 'backoff',      // این متد موقتاً غیرفعال
    6  => 'never',        // احراز هویت انجام نشده
    8  => 'never',        // اطلاعات هویتی ناقص
    9  => 'never',        // مقادیر ورودی نادرست
    10 => 'never',        // آی‌پی مجاز نیست
    11 => 'never',        // فرمت ApiKey نادرست
    12 => 'never',        // خط فرستنده نادرست
    13 => 'never',        // شمارهٔ گیرنده نامعتبر
    14 => 'never',        // دسترسی به متد ندارید
    15 => 'limit-reset',  // سقف روزانه
    16 => 'limit-reset',  // سقف API
    17 => 'limit-reset',  // سقف شبانه
    18 => 'limit-reset',  // سقف خط اشتراکی
    19 => 'never',        // اعتبار کافی نیست
    20 => 'backoff',      // تعداد درخواست بیش از حد
    100 => 'backoff',     // خطای داخلی سرور
];

/** never | backoff | limit-reset */
function pr_error_retry(int $code): string
{
    return PR_ERROR_RETRY[$code] ?? 'backoff';
}

/**
 * آیا تکرار همین درخواست بدون تغییر می‌تواند جواب بدهد.
 *
 * اگر false بود دوباره نفرستید؛ تکرار فقط سهمیهٔ نرخ را می‌سوزاند و در
 * نهایت به خطای ۲۰ می‌رسد.
 */
function pr_error_is_retryable(int $code): bool
{
    return pr_error_retry($code) !== 'never';
}
