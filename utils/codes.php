/**
 * تکلیف هر وضعیت با حلقهٔ استعلام.
 *
 *   pending    هنوز در راه است، بعداً دوباره استعلام کنید
 *   final      دیگر تغییر نمی‌کند، استعلام را متوقف کنید
 *   not-sent   اصلاً ارسال نشد، مانع را رفع و دوباره بفرستید
